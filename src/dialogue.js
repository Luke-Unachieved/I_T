export function dialogueScene(s,id,kind){
 const p=PEOPLE.find(p=>p.id===id);if(!p||!['chat','date'].includes(kind))return null;
 const i=s.relations[id][kind==='chat'?'chats':'dates']%3,first=s.dialogueMemories?.[id]?.[kind]?.[0];
 const branch=i===2&&first?`${kind}:${id}:${first.response}`:null;
 const base=branch?DIALOGUE_BRANCHES[kind][id][first.response]:p[kind==='chat'?'chats':'dates'][i];
 const scene=kind==='chat'&&s.stage==='founder'&&!s.staff.includes(id)&&i<2&&INDEPENDENT_CHAT[id]?INDEPENDENT_CHAT[id][i]:base;
 return {index:i,branch,scene,choices:(kind==='chat'?CHAT_REPLIES:DATE_REPLIES)[id][i]};
}
export function rememberDialogue(s,id,kind,scene,response){
 const records=s.dialogueMemories[id][kind];
 if(records[scene.index])return; // Keep the first recorded encounter, even after repeats.
 const answer=scene.choices[response];
 records[scene.index]={day:s.day,response,branch:scene.branch,scene:scene.scene,line:answer.line,reply:answer.reply};
}
